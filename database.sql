CREATE TABLE IF NOT EXISTS users (
	id INTEGER PRIMARY KEY,
	name TEXT NOT NULL UNIQUE,
	password TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS disk_types (
	id INTEGER PRIMARY KEY,
	name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS types (
	id INTEGER PRIMARY KEY,
	type TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS disk (
	id INTEGER PRIMARY KEY,
	title TEXT NOT NULL UNIQUE,
	disk_type_id INTEGER NOT NULL REFERENCES disk_types(id),
	year INT NOT NULL,
	run_time INT NOT NULL,
	genre TEXT NOT NULL,
	plot TEXT NOT NULL UNIQUE,
	poster TEXT NOT NULL UNIQUE,
	type INTEGER NOT NULL REFERENCES types(id)
);

CREATE TABLE IF NOT EXISTS rentals (
	user_id INTEGER NOT NULL REFERENCES users(id),
	disk_id INTEGER NOT NULL REFERENCES disk(id),
	PRIMARY KEY (user_id, disk_id)
);